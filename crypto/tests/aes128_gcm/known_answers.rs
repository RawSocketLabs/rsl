fn algorithm() -> Aes128Gcm {
    Aes128Gcm::new(Aes128GcmKey::new(KEY))
}

/// NIST `AES_GCM.pdf`, GCM-AES128 Example 1: empty AAD and plaintext.
#[test]
fn example_one_empty_inputs_match_the_published_tag() {
    let algorithm = algorithm();
    let nonce = Aes128GcmNonce::new(NONCE);
    let sealed = algorithm
        .seal(&nonce, &[], &[])
        .expect("empty inputs satisfy every GCM length limit");

    assert!(sealed.ciphertext().is_empty());
    assert_eq!(
        sealed.tag(),
        &Aes128GcmTag::new([
            0x32, 0x47, 0x18, 0x4b, 0x3c, 0x4f, 0x69, 0xa4, 0x4d, 0xbc, 0xd2, 0x28, 0x87, 0xbb,
            0xb4, 0x18,
        ])
    );
}

/// NIST `AES_GCM.pdf`, GCM-AES128 Example 5: partial AAD and plaintext blocks.
#[test]
fn example_five_matches_both_published_outputs_and_opens_them() {
    let algorithm = algorithm();
    let nonce = Aes128GcmNonce::new(NONCE);
    let sealed = algorithm
        .seal(&nonce, &ASSOCIATED_DATA[..20], &PLAINTEXT[..60])
        .expect("the published inputs satisfy every GCM length limit");

    assert_eq!(sealed.ciphertext(), &CIPHERTEXT[..60]);
    assert_eq!(
        sealed.tag(),
        &Aes128GcmTag::new([
            0xf0, 0x7c, 0x25, 0x28, 0xee, 0xa2, 0xfc, 0xa1, 0x21, 0x1f, 0x90, 0x5e, 0x1b, 0x6a,
            0x88, 0x1b,
        ])
    );

    let opened = algorithm
        .open(
            &nonce,
            &ASSOCIATED_DATA[..20],
            sealed.ciphertext(),
            sealed.tag(),
        )
        .expect("the published tag authenticates all published inputs");
    assert_eq!(opened, PLAINTEXT[..60]);
}
