//! Published AES-128 block vectors through the public API.

use rsl_crypto::cipher::aes::aes128::{Aes128, Aes128Block, Aes128Key};

/// Published complete-cipher evidence from FIPS 197-upd1 Appendix B.
#[test]
fn fips_appendix_b_encrypts_and_decrypts() {
    let key = Aes128Key::new([
        0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f,
        0x3c,
    ]);
    let plaintext = [
        0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d, 0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07,
        0x34,
    ];
    let ciphertext = [
        0x39, 0x25, 0x84, 0x1d, 0x02, 0xdc, 0x09, 0xfb, 0xdc, 0x11, 0x85, 0x97, 0x19, 0x6a, 0x0b,
        0x32,
    ];
    let cipher = Aes128::new(key);
    let mut block = Aes128Block::new(plaintext);

    cipher.encrypt_block(&mut block);
    assert_eq!(block.as_bytes(), &ciphertext);

    cipher.decrypt_block(&mut block);
    assert_eq!(block.as_bytes(), &plaintext);
}

/// Published four-block evidence from NIST's supplementary `AES_Core128.pdf`.
///
/// Each listed block is transformed independently. “ECB” identifies the source document's
/// presentation; this library does not expose an ECB multi-block mode.
#[test]
fn nist_core128_all_four_blocks_encrypt_and_decrypt() {
    let plaintexts = [
        [
            0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93,
            0x17, 0x2a,
        ],
        [
            0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf,
            0x8e, 0x51,
        ],
        [
            0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11, 0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a,
            0x52, 0xef,
        ],
        [
            0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17, 0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c,
            0x37, 0x10,
        ],
    ];
    let ciphertexts = [
        [
            0x3a, 0xd7, 0x7b, 0xb4, 0x0d, 0x7a, 0x36, 0x60, 0xa8, 0x9e, 0xca, 0xf3, 0x24, 0x66,
            0xef, 0x97,
        ],
        [
            0xf5, 0xd3, 0xd5, 0x85, 0x03, 0xb9, 0x69, 0x9d, 0xe7, 0x85, 0x89, 0x5a, 0x96, 0xfd,
            0xba, 0xaf,
        ],
        [
            0x43, 0xb1, 0xcd, 0x7f, 0x59, 0x8e, 0xce, 0x23, 0x88, 0x1b, 0x00, 0xe3, 0xed, 0x03,
            0x06, 0x88,
        ],
        [
            0x7b, 0x0c, 0x78, 0x5e, 0x27, 0xe8, 0xad, 0x3f, 0x82, 0x23, 0x20, 0x71, 0x04, 0x72,
            0x5d, 0xd4,
        ],
    ];
    let cipher = Aes128::new(Aes128Key::new([
        0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f,
        0x3c,
    ]));

    for (case, (plaintext, ciphertext)) in plaintexts.into_iter().zip(ciphertexts).enumerate() {
        let mut block = Aes128Block::new(plaintext);

        cipher.encrypt_block(&mut block);
        assert_eq!(block.as_bytes(), &ciphertext, "encryption block {case}");

        cipher.decrypt_block(&mut block);
        assert_eq!(block.as_bytes(), &plaintext, "decryption block {case}");
    }
}
