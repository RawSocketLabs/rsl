def planned(paths=(), **kwargs):
    graph = fixture()
    if kwargs.pop("release", False):
        kwargs["release_members"] = codec_members(graph)
    plan = select(paths, graph, graph, **kwargs)
    plan.update(base="a" * 40, head="b" * 40, release_candidate=False)
    return plan


def codec_members(graph):
    return [{"product": "bitsandbytes", "root": root, "name": graph[root].name,
             "version": graph[root].version} for root in sorted((BNB, MACROS))]


def results(plan):
    return {"plan": {"result": "success"}, "policy": {"result": "success"},
            "checks": {"result": "success" if plan["profiles"] else "skipped"},
            "fuzz": {"result": "success" if plan["fuzz"] else "skipped"}}


class SelectionTests(unittest.TestCase):
    def test_blessed_changes_select_facade_and_consumers_in_both_layouts(self):
        for root in ("deps", "deps"):
            graph = {root: Package("deps", set()), "consumer": Package("consumer", {root})}
            for path in (f"{root}/src/lib.rs", "tools/gen-blessed.py", "tools/check-drift.py",
                         ".github/actions/blessed-drift/action.yml"):
                with self.subTest(root=root, path=path):
                    plan = select([path], graph, graph)
                    self.assertFalse(plan["full"])
                    self.assertEqual(set(plan["packages"]), {"deps", "consumer"})
                    self.assertTrue({"blessed", "facades"} <= set(plan["profiles"]))
                    self.assertEqual(plan["fuzz"], [])

