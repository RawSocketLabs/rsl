class GitBoundaryTests(unittest.TestCase):
    def test_deleted_renamed_and_unusual_paths_survive_git_transport(self):
        with tempfile.TemporaryDirectory(prefix="rsl-ci-git-test-") as directory:
            root = Path(directory)
            def git(*args):
                return subprocess.run(["git", *args], cwd=root, check=True,
                                      stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout
            # No commits/hooks/identity are needed: immutable trees are enough for git diff.
            git("init", "--quiet")
            (root / "old name.rs").write_text("same contents\n")
            git("add", "old name.rs")
            old = git("write-tree").decode().strip()
            (root / "old name.rs").rename(root / "new\nname.rs")
            git("add", "--all")
            new = git("write-tree").decode().strip()
            self.assertEqual(changed_paths(root, old, new), ["new\nname.rs", "old name.rs"])


