import unittest

from release_sync import sync_text

LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "bitsandbytes"
version = "0.8.0"
dependencies = [
 "bitsandbytes-macros",
 "thiserror",
]

[[package]]
name = "bitsandbytes-macros"
version = "0.8.0"

[[package]]
name = "thiserror"
version = "0.8.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "fuzz"
version = "0.0.0"
dependencies = [
 "bitsandbytes",
]
"""


class SyncTests(unittest.TestCase):
    def test_path_members_take_the_workspace_version_and_nothing_else_changes(self):
        versions = {"bitsandbytes": "0.8.1", "bitsandbytes-macros": "0.8.1", "thiserror": "9.9.9"}
        expected = (LOCK.replace('name = "bitsandbytes"\nversion = "0.8.0"',
                                 'name = "bitsandbytes"\nversion = "0.8.1"')
                    .replace('name = "bitsandbytes-macros"\nversion = "0.8.0"',
                             'name = "bitsandbytes-macros"\nversion = "0.8.1"'))
        self.assertEqual(sync_text(LOCK, versions), expected)

    def test_an_in_step_lockfile_is_untouched(self):
        self.assertEqual(sync_text(LOCK, {"bitsandbytes": "0.8.0", "fuzz": "0.0.0"}), LOCK)

    def test_shapes_a_plain_rewrite_cannot_handle_fail_closed(self):
        cases = {"path and registry": LOCK.replace('name = "thiserror"', 'name = "bitsandbytes"'),
                 "two paths": LOCK.replace('name = "fuzz"', 'name = "bitsandbytes"'),
                 "CRLF": LOCK.replace("\n", "\r\n"),
                 "format 3": LOCK.replace("version = 4", "version = 3")}
        for case, lock in cases.items():
            with self.subTest(case=case), self.assertRaises(ValueError):
                sync_text(lock, {"bitsandbytes": "0.8.1"})


if __name__ == "__main__":
    unittest.main()
