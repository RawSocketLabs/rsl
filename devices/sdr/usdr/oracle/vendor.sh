#!/usr/bin/env bash
# Refresh the vendored libusdr subset from an upstream checkout at the commit in libusdr/PIN.
#
# Usage: vendor.sh [--usb-only] <path-to-usdr-lib-checkout>
# --usb-only refreshes only the exported USB RX/TX reference functions (libusdr/reference).
# Needs git, python3 and PyYAML (upstream's register-header generator).
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
usb_only=false
if [[ ${1:-} == --usb-only ]]; then
    usb_only=true
    shift
fi
upstream=$(cd "$1" && pwd)
dest="$here/libusdr"
pin=$(cat "$dest/PIN")

head=$(git -C "$upstream" rev-parse HEAD)
if [[ "$head" != "$pin" ]]; then
    echo "upstream checkout is at $head, PIN is $pin" >&2
    exit 1
fi

src="$upstream/src"
# A dirty checkout must not masquerade as evidence from the committed PIN.
git -C "$upstream" diff --quiet "$pin" -- src/lib/lowlevel/usb_uram/usb_uram_libusb.c
# Export the original static USB RX and TX functions without their libusb plugin
# scaffolding. This is generated reference code, not a second implementation of framing.
mkdir -p "$dest/reference"
python3 - "$src/lib/lowlevel/usb_uram/usb_uram_libusb.c" "$dest/reference" "$pin" <<'PY'
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text()
reference = pathlib.Path(sys.argv[2])

def balanced(start):
    opening = source.index("{", start)
    depth = 1
    end = opening + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return end

def declaration(start):
    return source[start:source.index(";", balanced(start)) + 1]

def functions(*names):
    for name in names:
        match = re.search(r"^static\s*\n(?:uint32_t\s*\*\s*|(?:void|int)\s+)" + name + r"\(", source, re.MULTILINE)
        if match is None:
            raise SystemExit(f"missing pinned USB function: {name}")
        yield source[match.start():balanced(match.start())]

enums = [declaration(match.start()) for match in list(re.finditer(r"^enum \{", source, re.MULTILINE))[:2]]
params = re.search(r"^struct stream_params \{", source, re.MULTILINE)
if params is None:
    raise SystemExit("missing pinned struct stream_params")
# usb_async_start otherwise sets up libusb transfers: keep only its TX statistics lines.
start = re.search(r"^int usb_async_start\(", source, re.MULTILINE)
if start is None:
    raise SystemExit("missing pinned usb_async_start")
stat_lines = re.findall(r"^\s*dev->tx_stat_\w+ = [^;]*;.*$", source[start.start():balanced(start.start())], re.MULTILINE)
if len(stat_lines) != 2:
    raise SystemExit("missing pinned TX statistics initialisation in usb_async_start")
tx_stat = (
    "// The TX statistics lines of usb_async_start, verbatim.\n"
    "static void usb_async_start_tx_stat(usb_dev_t* dev)\n{\n" + "\n".join(stat_lines) + "\n}"
)
header = (
    "// Copyright (c) 2023-2024 Wavelet Lab\n// SPDX-License-Identifier: MIT\n"
    f"// Generated by oracle/vendor.sh from usb_uram_libusb.c at {sys.argv[3]}.\n"
    "// Do not edit; refresh from the pinned upstream checkout.\n\n"
)
def write(name, pieces):
    (reference / name).write_text(header + "\n\n".join(pieces) + "\n")

write("usb_rx.inc", enums + list(functions(
    "_get_trailer_bursts", "_usb_uram_stream_on_buffer", "_usb_uram_init_rxstream",
    "usb_uram_recv_dma_wait", "usb_uram_recv_dma_release", "usb_uram_stream_deinitialize",
)))
# The shim's device holds the TX parameters, so their type is included before it.
write("usb_tx_params.inc", [declaration(params.start())])
write("usb_tx.inc", enums + [tx_stat] + list(functions(
    "_usb_uram_init_txstream", "usb_uram_send_dma_get", "usb_uram_send_dma_commit",
    "usb_uram_stream_deinitialize",
)))
PY
if $usb_only; then
    echo "exported USB RX/TX reference at $pin"
    exit 0
fi
rm -rf "$dest/lib" "$dest/gen"
mkdir -p "$dest/lib" "$dest/gen"

# The hardware transports (USB, PCIe, FT601, WebUSB, Verilator) are replaced by the sim plugin
# in shim/; everything else in src/lib is kept so libusdr's device registry links unmodified.
# The register YAMLs are kept too: they are the generated headers' source and document every field.
(cd "$src/lib" && find . \( -name '*.c' -o -name '*.h' -o -name '*.t' -o -name '*.inc' -o -name '*.yaml' \) \
    -not -path './lowlevel/usb_uram/*' -not -path './lowlevel/pcie_uram/*' \
    -not -path './lowlevel/usb_ft601/*' -not -path './lowlevel/verilator_ll/*' \
    -not -path './webusb/*' -not -path '*/utests/*' \
    -not -name 'libusb_generic.[ch]' -not -name 'test_*' -print0 \
    | xargs -0 cp --parents -t "$dest/lib")
# usdr_lowlevel.c includes this USB header for its declarations only.
(cd "$src/lib" && cp --parents lowlevel/usb_uram/usb_uram_generic.h "$dest/lib")
# The PCIe driver's userspace interface ((GPL-2.0 WITH Linux-syscall-note) OR MIT): the oracle
# checks rsl-usdr-pcie's ioctl numbers, struct layouts and uSDR device layout against it.
(cd "$src/lib" && cp --parents lowlevel/pcie_uram/pcie_uram_driver_if.h "$dest/lib")

# Register headers upstream generates at CMake time from YAML.
gen() { python3 "$src/hwparser/gen_h.py" --yaml "$1" --ch "$dest/gen/def_$2.h" > "$dest/gen/def_$2.h"; }
for y in "$src"/lib/hw/*/*.yaml; do
    name=$(basename "$y" .yaml)
    [[ "$(basename "$(dirname "$y")")" == "$name" ]] && gen "$y" "$name"
done
for d in m2_dsdr ext_xmass ext_pciefe ext_fe_ch4_400_7200 ext_fe_100_5000; do
    for y in "$src/lib/device/$d"/*.yaml; do
        gen "$y" "$(basename "$y" .yaml)"
    done
done

cp "$upstream/LICENSE" "$dest/LICENSE"
(cd "$dest/lib" && find . -name '*.c' -not -path '*/templates/*' | sed 's|^\./||' | LC_ALL=C sort) > "$dest/sources.txt"
echo "vendored $(wc -l < "$dest/sources.txt") sources at $pin"
