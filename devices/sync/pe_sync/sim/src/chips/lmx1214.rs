//! The LMX1214 LO buffer and divider (`hw/lmx1214/lmx1214.c`): `LoDistrib` on SPI bus 5
//! (`SPI_LMX1214` in `pe_sync.c`).

use super::spi::{Reset, SpiRegisters};

/// The documented registers' reset values and read-only masks, from the `dflt` and `mode`
/// of each field in the pinned `hw/lmx1214/lmx1214.yaml`. Other addresses reset to 0.
#[rustfmt::skip]
const RESET: [Reset; 20] = [
    (0x00, 0x0000, 0xfff8), (0x02, 0x0223, 0xf800), (0x03, 0xf0fe, 0x0000), (0x04, 0x36ff, 0xc000),
    (0x05, 0x36f6, 0x8000), (0x07, 0x543f, 0x8000), (0x08, 0x0110, 0xfe00), (0x09, 0x0020, 0x0000),
    (0x0b, 0x0000, 0xffff), (0x0c, 0x0000, 0xffff), (0x0d, 0x0003, 0xfffc), (0x0e, 0x0002, 0x0000),
    (0x0f, 0x0b01, 0xf000), (0x17, 0x4000, 0x0000), (0x18, 0x0000, 0xcffe), (0x19, 0x0211, 0x0000),
    (0x4b, 0x0006, 0xfff0), (0x4f, 0x0205, 0x8000), (0x56, 0x0000, 0x0000), (0x5a, 0x0000, 0xff00),
];

/// An LMX1214 fresh out of power-on reset. libusdr polls nothing on it: it reads the
/// temperature (`R24`, logged only) and read-modify-writes `R25`.
pub(crate) fn lmx1214() -> SpiRegisters {
    SpiRegisters::new(&RESET)
}
